// capitalFont uses seven visible rows and two blank rows, like the lowercase
// glyphs. Compact letters retain the same two-column pixel geometry.
func capitalFont(compact bool) map[rune]Glyph {
	wide := []string{
		".###./#...#/#...#/#####/#...#/#...#/#...#", "####./#...#/#...#/####./#...#/#...#/####.",
		".####/#..../#..../#..../#..../#..../.####", "####./#...#/#...#/#...#/#...#/#...#/####.",
		"#####/#..../#..../####./#..../#..../#####", "#####/#..../#..../####./#..../#..../#....",
		".####/#..../#..../#.###/#...#/#...#/.###.", "#...#/#...#/#...#/#####/#...#/#...#/#...#",
		"###/.#./.#./.#./.#./.#./###", "..###/...#./...#./...#./...#./#..#./.##..",
		"#...#/#..#./#.#../##.../#.#../#..#./#...#", "#..../#..../#..../#..../#..../#..../#####",
		"#...#/##.##/#.#.#/#...#/#...#/#...#/#...#", "#...#/##..#/#.#.#/#..##/#...#/#...#/#...#",
		".###./#...#/#...#/#...#/#...#/#...#/.###.", "####./#...#/#...#/####./#..../#..../#....",
		".###./#...#/#...#/#...#/#.#.#/#..#./.##.#", "####./#...#/#...#/####./#.#../#..#./#...#",
		".####/#..../#..../.###./....#/....#/####.", "#####/..#../..#../..#../..#../..#../..#..",
		"#...#/#...#/#...#/#...#/#...#/#...#/.###.", "#...#/#...#/#...#/#...#/#...#/.#.#./..#..",
		"#...#/#...#/#...#/#...#/#.#.#/##.##/#...#", "#...#/#...#/.#.#./..#../.#.#./#...#/#...#",
		"#...#/#...#/.#.#./..#../..#../..#../..#..", "#####/....#/...#./..#../.#.../#..../#####",
	}
	narrow := []string{
		".#./#.#/#.#/###/#.#/#.#/#.#", "##./#.#/#.#/##./#.#/#.#/##.",
		".##/#../#../#../#../#../.##", "##./#.#/#.#/#.#/#.#/#.#/##.",
		"###/#../#../##./#../#../###", "###/#../#../##./#../#../#..",
		".##/#../#../#.#/#.#/#.#/.##", "#.#/#.#/#.#/###/#.#/#.#/#.#",
		"#/#/#/#/#/#/#", "..#/..#/..#/..#/..#/#.#/.#.",
		"#.#/#.#/#.#/##./#.#/#.#/#.#", "#../#../#../#../#../#../###",
		"#.#/###/###/#.#/#.#/#.#/#.#", "#.#/###/###/###/#.#/#.#/#.#",
		".#./#.#/#.#/#.#/#.#/#.#/.#.", "##./#.#/#.#/##./#../#../#..",
		".#./#.#/#.#/#.#/#.#/.#./..#", "##./#.#/#.#/##./#.#/#.#/#.#",
		".##/#../#../.#./..#/..#/##.", "###/.#./.#./.#./.#./.#./.#.",
		"#.#/#.#/#.#/#.#/#.#/#.#/###", "#.#/#.#/#.#/#.#/#.#/#.#/.#.",
		"#.#/#.#/#.#/#.#/###/###/#.#", "#.#/#.#/#.#/.#./#.#/#.#/#.#",
		"#.#/#.#/#.#/.#./.#./.#./.#.", "###/..#/..#/.#./#../#../###",
	}
	if compact {
		wide = narrow
	}
	out := make(map[rune]Glyph, len(wide))
	for i, rows := range wide {
		var g Glyph
		copy(g[:], strings.Split(rows, "/"))
		out[rune('A'+i)] = g
	}
	return out
}
